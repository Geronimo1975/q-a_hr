from django.utils.translation import get_language, activate
from django.utils.deprecation import MiddlewareMixin
from django.conf import settings
from utils.translate_api import translate_text
import re

class GoogleTranslationMiddleware(MiddlewareMixin):
    """
    Middleware that integrates Google Translation with Django's translation system.
    This allows for automatic fallback to Google Translate when Django translations are missing.
    """

    def __init__(self, get_response=None):
        self.get_response = get_response
        # Initialize storage for translation tracking
        self.translation_cache = {}
        
        # HTML tags to ignore during translation
        self.html_pattern = re.compile(r'<.*?>')

    def process_request(self, request):
        """Process the request and set the language"""
        language_code = get_language()
        if language_code:
            activate(language_code)
        return None
    
    def process_template_response(self, request, response):
        """Process response for template responses to translate missing translations"""
        # We hook into template response to translate content
        # This is particularly useful for dynamic content generated by templates
        if hasattr(response, 'context_data') and isinstance(response.context_data, dict):
            language_code = get_language()
            if language_code == 'de':  # Skip translation for German (our base language)
                return response
                
            # Here we could insert code to translate the context data
            # But the translation is now primarily done through template tags
                
        return response
    
    def process_response(self, request, response):
        """Clean up after each request"""
        # For non-HTML responses or responses with specific content types, we skip translation
        content_type = response.get('Content-Type', '')
        if not content_type.startswith('text/html'):
            return response
            
        return response
        
    def translate_content(self, content, target_language):
        """Translate HTML content preserving HTML tags"""
        if not content or not target_language:
            return content
            
        # To properly translate HTML content, we would need to:
        # 1. Parse the HTML to separate text nodes from tags
        # 2. Translate only the text nodes
        # 3. Reconstruct the HTML with translated text nodes
        
        # For simplicity in this example, we're using regex to split by HTML tags
        # A production implementation should use a proper HTML parser
        fragments = self.html_pattern.split(content)
        tags = self.html_pattern.findall(content)
        
        # Translate only the text fragments (not HTML tags)
        translated_fragments = []
        for i, fragment in enumerate(fragments):
            if fragment.strip():
                cache_key = f"{fragment}:{target_language}"
                if cache_key in self.translation_cache:
                    translated_fragment = self.translation_cache[cache_key]
                else:
                    translated_fragment = translate_text(fragment, target_language)
                    self.translation_cache[cache_key] = translated_fragment
                translated_fragments.append(translated_fragment)
            else:
                translated_fragments.append(fragment)
        
        # Reconstruct with HTML tags
        result = []
        for i in range(len(translated_fragments)):
            result.append(translated_fragments[i])
            if i < len(tags):
                result.append(tags[i])
                
        return ''.join(result)